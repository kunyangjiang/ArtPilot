/**
 * When a work was made. `precision` says what kind of date it is:
 * year — one documented year (a dated inscription, a signed and dated work);
 * range — documented years from and to (a reign, a building campaign, a dated series);
 * approx — about these years (a museum's 约, a style-based dating);
 * century — a century or part of one;
 * period — a dynasty, culture or era, with only round years;
 * disputed — sources disagree, or the dating itself is in question;
 * deep — prehistory: a minimum age or the age of a layer, not the date the image was made.
 * `label` is the date as written for this entry; a work's own record keeps its full dating.
 */
export type Precision = 'year' | 'range' | 'approx' | 'century' | 'period' | 'disputed' | 'deep';
export type When = { from: number; to: number; precision: Precision; label: string };
/** Where it was made: an anchor, or none when the place cannot be determined; `detail` names it more closely. */
export type Place = { anchor: string | null; detail: string; precision: 'site' | 'city' | 'region' | 'tradition' | 'unknown' };
/** A source: an outside page or publication, or one of the site's own lessons or articles (titled from the collection). */
export type Source = { label?: string; url?: string; lesson?: string; essay?: string };

export type Entry = {
  /** An artwork record's id, or a context entry's id (ctx-…). */
  id: string;
  place: Place;
  when: When;
  /** What kind of thing it is, in a few words. */
  form: string;
  /** The tradition or polity it belongs to, as named in its own context. */
  tradition: string;
  note: string;
};

